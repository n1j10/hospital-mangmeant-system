// Every action returns an object like this
type ActionResult = { message: string };

// Turn an error into { message } so the form can show it
function renderError(error: unknown): ActionResult {
  console.log("SERVER ACTION ERROR:", error);
  return {
    message: error instanceof Error ? error.message : "Unknown Error",
  };
}

// "contains" search that ignores uppercase/lowercase
function contains(text: string) {
  return { contains: text, mode: "insensitive" as const };
}

// Returns the start of today and the start of tomorrow
function getTodayRange() {
  const start = new Date();
  start.setHours(0, 0, 0, 0);
  const end = new Date(start);
  end.setDate(end.getDate() + 1);
  return { start, end };
}

// Returns the date after X days from now
function getDateAfterDays(days: number) {
  const date = new Date();
  date.setDate(date.getDate() + days);
  return date;
}

// "Low stock" means: quantity <= lowStockThreshold of the same medicine
const lowStockFilter = {
  quantity: { lte: db.medicine.fields.lowStockThreshold },
};

// Used a lot: load the doctor together with his user (name, email...)
const doctorWithUser = { include: { user: true } };

// ─── Forms that are used in both create and update ───

function readPatientForm(formData: FormData) {
  const data = validateFuctionSchema(patientSchema, Object.fromEntries(formData));
  return {
    fullName: data.fullName,
    gender: data.gender as Gender,
    dateOfBirth: new Date(data.dateOfBirth),
    phone: data.phone,
    address: data.address || null,
    bloodType: data.bloodType || null,
  };
}

function readMedicineForm(formData: FormData) {
  const data = validateFuctionSchema(medicineSchema, Object.fromEntries(formData));
  return {
    name: data.name,
    categoryId: data.categoryId,
    quantity: data.quantity,
    unit: data.unit || null,
    price: data.price,
    expiryDate: new Date(data.expiryDate),
    lowStockThreshold: data.lowStockThreshold,
  };
}

