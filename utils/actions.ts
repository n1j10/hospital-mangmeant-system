export async function createConsultationAction(
  _prevState: unknown,
  formData: FormData
): Promise<ActionResult> {
  try {
    const data = validateFuctionSchema(consultationSchema, Object.fromEntries(formData));

    // Two things must happen together:
    // 1. create the consultation
    // 2. mark the appointment as COMPLETED
    // $transaction means: if one fails, both are cancelled
    await db.$transaction([
      db.consultation.create({
        data: {
          appointmentId: data.appointmentId,
          patientId: data.patientId,
          doctorId: data.doctorId,
          diagnosis: data.diagnosis || null,
          notes: data.notes || null,
        },
      }),
      db.appointment.update({
        where: { id: data.appointmentId },
        data: { status: "COMPLETED" },
      }),
    ]);

    revalidatePath("/consultations");
    revalidatePath("/appointments");
    return { message: "Consultation created successfully" };
  } catch (error) {
    return renderError(error);
  }
}

